/**
  * @brief This function handles USART1 global interrupt / USART1 wake-up interrupt through EXTI line 25.
  */
void USART1_IRQHandler(void)
{
  /* USER CODE BEGIN USART1_IRQn 0 */

	if (__HAL_UART_GET_FLAG(&huart1, UART_FLAG_IDLE))	
	{                               // 1. 获得串口空闲中断标志	
		__HAL_UART_CLEAR_FLAG(&huart1,UART_CLEAR_IDLEF);													 // 2. 清除空闲中断标志
		HAL_UART_DMAStop(&huart1);	 // 3. 清除->空闲->停止DMA		
		len = 64 - hdma_usart1_rx.Instance->CNDTR;
            // 4. 设定的传输长度-剩余传输数量（DMA_CNDTRx）=实际长度
		buf_ctl[len]='\0';
		HAL_UART_Transmit(&huart1,buf_ctl,sizeof(buf_ctl),500);
		sscanf(buf_ctl,"SET:T_up=%dT_low=%dH_up=%dH_low=%d",&T_up,&T_low,&H_up,&H_low);
//		printf("th=%d %d %d %d\n",T_up,T_low,H_up,H_low);
		Threshold_t_conf[0]=T_up;
		Threshold_t_conf[1]=T_low;
		Threshold_h_conf[0]=H_up;
		Threshold_h_conf[1]=H_low;	
		
		Threshold_t_set[0]=T_up;
		Threshold_t_set[1]=T_low;
		Threshold_h_set[0]=H_up;
		Threshold_h_set[1]=H_low;
		memset(buf_ctl,0,sizeof(buf_ctl));
		HAL_UART_Receive_DMA(&huart1, buf_ctl, 64);
								     // 6. 重新开启DMA
	}
	
  /* USER CODE END USART1_IRQn 0 */
  HAL_UART_IRQHandler(&huart1);
  /* USER CODE BEGIN USART1_IRQn 1 */

  /* USER CODE END USART1_IRQn 1 */
}

